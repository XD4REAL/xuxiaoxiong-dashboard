def get_today_info():
    """获取今天的日期信息，用于bot上下文中"""
    tz = datetime.timezone(datetime.timedelta(hours=8))
    now = datetime.datetime.now(tz)
    today = now.strftime("%Y-%m-%d")
    today_cn = f"{now.year}年{now.month}月{now.day}日 {now.strftime('%H:%M')}"

    # 查找今天是不是纪念日
    today_events = []
    upcoming_events = []

    for ann in ANNIVERSARIES:
        ann_date = datetime.datetime.strptime(ann["date"], "%Y-%m-%d").date()
        ann_this_year = ann_date.replace(year=now.year)

        if ann_this_year == now.date():
            days_since = (now.date() - ann_date).days
            today_events.append({
                "name": ann["name"],
                "days_since": days_since,
                "event": ann.get("event", ""),
                "phrase": ann.get("phrase", ""),
            })

        # 未来30天内的纪念日
        elif ann_this_year > now.date() and (ann_this_year - now.date()).days <= 30:
            days_until = (ann_this_year - now.date()).days
            upcoming_events.append({
                "name": ann["name"],
                "date": ann_this_year.strftime("%m月%d日"),
                "days_until": days_until,
                "event": ann.get("event", ""),
            })

    return {
        "today": today,
        "today_cn": today_cn,
        "today_events": today_events,
        "upcoming_events": upcoming_events,
    }